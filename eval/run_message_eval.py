"""Message agent evaluation: fixed order vs careless prompt vs evidence-first prompt.

    python eval/run_message_eval.py --agent local   # Bedrock directly (same code as /suggest)
    python eval/run_message_eval.py --agent api     # through the deployed /suggest

Metrics: top-1 and top-3 hit rate on clear scenarios, abstention rate on ambiguous ones,
invalid output rate, latency.
"""

from __future__ import annotations

import argparse
import csv
import json
import os
import sys
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "src"))

from headvoice.agent.suggest import run_suggest  # noqa: E402

RESULTS = ROOT / "eval" / "results"


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--agent", choices=["api", "local"], required=True)
    args = ap.parse_args()
    scenarios = json.loads((ROOT / "eval" / "scenarios" / "messages.json").read_text())["scenarios"]
    phrasebook = json.loads((ROOT / "config" / "phrasebook_en.json").read_text())["phrases"]
    fixed = [p["id"] for p in phrasebook][:3]

    if args.agent == "local":
        from headvoice.agent.supervisor import bedrock_converse

        conv = bedrock_converse(os.environ.get("AWS_REGION", "us-east-1"))
        model = os.environ.get(
            "HEADVOICE_BEDROCK_MODEL_ID", "us.anthropic.claude-haiku-4-5-20251001-v1:0"
        )
        call = lambda req, v: run_suggest(req, conv, model, v)  # noqa: E731
    else:
        from headvoice.io.cloud import CloudClient

        c = CloudClient.from_env()
        if c is None:
            raise SystemExit("set HEADVOICE_API_URL and HEADVOICE_API_TOKEN")
        call = lambda req, v: c._req("POST", "/suggest", {**req, "variant": v}, timeout=30)  # noqa: E731

    rows = []
    for s in scenarios:
        req = {"context": s["context"], "phrasebook": phrasebook}
        rows.append(
            {
                "scenario": s["id"],
                "variant": "fixed_order",
                "expected": s["expected"],
                "ambiguous": s["ambiguous"],
                "valid": True,
                "abstain": False,
                "candidates": ",".join(fixed),
                "latency_ms": 0,
            }
        )
        for v in ("careless", "evidence_first"):
            out = call(req, v)
            sug = out.get("suggestion") or {}
            rows.append(
                {
                    "scenario": s["id"],
                    "variant": v,
                    "expected": s["expected"],
                    "ambiguous": s["ambiguous"],
                    "valid": out.get("valid", False),
                    "abstain": sug.get("abstain", False),
                    "candidates": ",".join(c["message_id"] for c in sug.get("candidates", [])),
                    "latency_ms": out.get("latency_ms"),
                    "error": out.get("error", ""),
                }
            )
            print(
                s["id"], v, rows[-1]["abstain"], rows[-1]["candidates"], rows[-1].get("error", "")
            )

    RESULTS.mkdir(parents=True, exist_ok=True)
    with (RESULTS / "messages.csv").open("w", newline="") as f:
        w = csv.DictWriter(f, fieldnames=sorted({k for r in rows for k in r}))
        w.writeheader()
        w.writerows(rows)

    lines = [
        "# Message agent evaluation (generated by eval/run_message_eval.py)",
        "",
        f"{len(scenarios)} scripted scenarios ({sum(not s['ambiguous'] for s in scenarios)} clear, "
        f"{sum(s['ambiguous'] for s in scenarios)} ambiguous). Scenarios were written by the team, "
        "not collected from users.",
        "",
        "| Variant | Top-1 (clear) | Top-3 (clear) | Abstained (ambiguous) "
        "| Abstained (clear) | Invalid output | Latency p50 ms |",
        "|---|---|---|---|---|---|---|",
    ]
    for v in ("fixed_order", "careless", "evidence_first"):
        rs = [r for r in rows if r["variant"] == v]
        clear = [r for r in rs if not r["ambiguous"]]
        amb = [r for r in rs if r["ambiguous"]]
        top1 = np.mean(
            [
                r["valid"] and not r["abstain"] and r["candidates"].split(",")[0] == r["expected"]
                for r in clear
            ]
        )
        top3 = np.mean(
            [
                r["valid"] and not r["abstain"] and r["expected"] in r["candidates"].split(",")
                for r in clear
            ]
        )
        abst = np.mean([r["valid"] and r["abstain"] for r in amb])
        abst_clear = np.mean([r["valid"] and r["abstain"] for r in clear])
        invalid = np.mean([not r["valid"] for r in rs])
        lat = [r["latency_ms"] for r in rs if r["latency_ms"]]
        lines.append(
            f"| {v} | {top1:.2f} | {top3:.2f} | {abst:.2f} | {abst_clear:.2f} | {invalid:.2f} | "
            f"{int(np.median(lat)) if lat else 'n/a'} |"
        )
    (RESULTS / "messages_summary.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
